// @vitest-environment jsdom
import {act} from 'react';
import {createRoot,type Root} from 'react-dom/client';
import {beforeEach,afterEach,expect,it,vi} from 'vitest';
import AnnouncementCenter from './AnnouncementCenter';
import {setLanguage} from './i18n';
let host:HTMLDivElement,root:Root,header:HTMLElement,toolbar:HTMLSpanElement;
const older={id:'old',title:'Older notice',body:'Old body',revision:1,publishedAt:'2026-10-10T10:00:00Z'};
const latest={id:'latest',title:'Latest notice',body:'Latest body',revision:1,publishedAt:'2026-10-11T10:00:00Z'};
beforeEach(()=>{setLanguage('en');localStorage.clear();header=document.createElement('header');toolbar=document.createElement('span');const help=document.createElement('button');help.textContent='Help';header.append(toolbar,help);host=document.createElement('div');document.body.append(header,host);root=createRoot(host);Object.assign(globalThis,{IS_REACT_ACT_ENVIRONMENT:true});});
afterEach(async()=>{await act(async()=>root.unmount());host.remove();header.remove();vi.unstubAllGlobals();});
it('shows only latest, dismisses persistently, and displays a newly published item',async()=>{
 await act(async()=>root.render(<AnnouncementCenter announcements={[older,latest]} toolbarTarget={toolbar}/>));
 expect(toolbar.querySelector('button')).toBeNull();
 expect(host.querySelector('[role=status]')?.textContent).toContain('Latest notice');
 expect(host.querySelector('[role=status]')?.textContent).not.toContain('Older notice');
 await act(async()=>host.querySelector<HTMLButtonElement>('[aria-label="Dismiss announcement"]')!.click());
 expect(host.querySelector('[role=status]')).toBeNull();
 expect(host.querySelector('.announcement-more')).toBeNull();
 expect(toolbar.querySelector('.announcement-trigger')).not.toBeNull();
 await act(async()=>root.render(<AnnouncementCenter key="remount" announcements={[older,latest]} toolbarTarget={toolbar}/>));
 expect(host.querySelector('[role=status]')).toBeNull();
 expect(toolbar.querySelector('.announcement-trigger')).not.toBeNull();
 await act(async()=>root.render(<AnnouncementCenter key="remount" announcements={[older,latest,{...latest,id:'new',title:'New notice',publishedAt:'2026-10-12T10:00:00Z'}]} toolbarTarget={toolbar}/>));
 expect(host.querySelector('[role=status]')?.textContent).toContain('New notice');
 expect(toolbar.querySelector('button')).toBeNull();
});
it('more opens all announcements newest first and Escape closes history',async()=>{
 await act(async()=>root.render(<AnnouncementCenter announcements={[older,latest]} toolbarTarget={toolbar}/>));
 await act(async()=>host.querySelector<HTMLButtonElement>('[aria-label="View all announcements"]')!.click());
 const dialog=document.querySelector('[role=dialog]')!;
 expect(Array.from(dialog.querySelectorAll('article h3')).map(n=>n.textContent)).toEqual(['Latest notice','Older notice']);
 await act(async()=>document.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true})));
 expect(document.querySelector('[role=dialog]')).toBeNull();
});
it('moves dismissed announcements before Help and opens history with focus returning to the icon',async()=>{
 await act(async()=>root.render(<AnnouncementCenter announcements={[older,latest]} toolbarTarget={toolbar}/>));
 await act(async()=>host.querySelector<HTMLButtonElement>('[aria-label="Dismiss announcement"]')!.click());
 const button=toolbar.querySelector<HTMLButtonElement>('[aria-label="View all announcements"]')!;
 expect(button.title).toBe('Announcements');
 expect(button.querySelector('svg.lucide-megaphone')).not.toBeNull();
 expect(toolbar.nextElementSibling?.textContent).toBe('Help');
 expect(document.activeElement).toBe(button);
 await act(async()=>button.click());
 expect(button.getAttribute('aria-expanded')).toBe('true');
 expect(Array.from(document.querySelectorAll('[role=dialog] article h3')).map(n=>n.textContent)).toEqual(['Latest notice','Older notice']);
 await act(async()=>document.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true})));
 expect(document.querySelector('[role=dialog]')).toBeNull();
 expect(button.getAttribute('aria-expanded')).toBe('false');
 expect(document.activeElement).toBe(button);
});
it('does not display an announcement icon or banner without announcements',async()=>{
 await act(async()=>root.render(<AnnouncementCenter announcements={[]} toolbarTarget={toolbar}/>));
 expect(host.textContent).toBe('');
 expect(toolbar.childElementCount).toBe(0);
});
it('loads ten announcements per batch on scroll, prevents duplicate loads, and resets on reopen',async()=>{
 let frame:FrameRequestCallback|undefined;
 const requestFrame=vi.fn((callback:FrameRequestCallback)=>{frame=callback;return 1;});
 vi.stubGlobal('requestAnimationFrame',requestFrame);
 vi.stubGlobal('cancelAnimationFrame',vi.fn(()=>{frame=undefined;}));
 const items=Array.from({length:21},(_,i)=>({...latest,id:`notice-${i}`,title:`Notice ${i}`,publishedAt:new Date(Date.UTC(2026,9,11,10,i)).toISOString()}));
 await act(async()=>root.render(<AnnouncementCenter announcements={items} toolbarTarget={toolbar}/>));
 const opener=host.querySelector<HTMLButtonElement>('[aria-label="View all announcements"]')!;
 await act(async()=>opener.click());
 const list=host.querySelector<HTMLDivElement>('.announcements-list')!;
 Object.defineProperties(list,{scrollHeight:{value:1200,configurable:true},clientHeight:{value:400,configurable:true},scrollTop:{value:0,writable:true}});
 expect(list.querySelectorAll('article')).toHaveLength(10);
 expect(list.querySelector('h3')?.textContent).toBe('Notice 20');
 await act(async()=>list.dispatchEvent(new Event('scroll',{bubbles:true})));
 expect(requestFrame).not.toHaveBeenCalled();
 list.scrollTop=800;
 await act(async()=>{list.dispatchEvent(new Event('scroll',{bubbles:true}));list.dispatchEvent(new Event('scroll',{bubbles:true}));});
 expect(requestFrame).toHaveBeenCalledTimes(1);
 expect(list.getAttribute('aria-busy')).toBe('true');
 expect(list.textContent).toContain('Loading more announcements');
 await act(async()=>{frame!(0);frame=undefined;});
 expect(list.querySelectorAll('article')).toHaveLength(20);
 expect(list.getAttribute('aria-busy')).toBe('false');
 await act(async()=>list.dispatchEvent(new Event('scroll',{bubbles:true})));
 await act(async()=>{frame!(0);frame=undefined;});
 expect(list.querySelectorAll('article')).toHaveLength(21);
 expect(list.textContent).toContain('All announcements loaded');
 await act(async()=>list.dispatchEvent(new Event('scroll',{bubbles:true})));
 expect(requestFrame).toHaveBeenCalledTimes(2);
 await act(async()=>host.querySelector<HTMLButtonElement>('[aria-label="Close panel"]')!.click());
 await act(async()=>opener.click());
 expect(host.querySelectorAll('.announcements-list article')).toHaveLength(10);
});
it('cancels pending pagination when the history modal closes',async()=>{
 const cancelFrame=vi.fn();
 vi.stubGlobal('requestAnimationFrame',vi.fn(()=>7));
 vi.stubGlobal('cancelAnimationFrame',cancelFrame);
 const items=Array.from({length:15},(_,i)=>({...latest,id:`notice-${i}`}));
 await act(async()=>root.render(<AnnouncementCenter announcements={items} toolbarTarget={toolbar}/>));
 await act(async()=>host.querySelector<HTMLButtonElement>('[aria-label="View all announcements"]')!.click());
 await act(async()=>host.querySelector('.announcements-list')!.dispatchEvent(new Event('scroll',{bubbles:true})));
 await act(async()=>host.querySelector<HTMLButtonElement>('[aria-label="Close panel"]')!.click());
 expect(cancelFrame).toHaveBeenCalledWith(7);
 expect(host.querySelector('[role=dialog]')).toBeNull();
});
